def test_linker_does_not_mutate_its_input_claim() -> None:
    task = loader.load_task(TASKS_DIR / "table_claims" / "accuracy_improvement.yaml")
    extracted = RuleBasedClaimExtractor().extract(task.input_claim, task.bundle)
    before = extracted.claim.model_copy(deep=True)
    result = EvidenceLinker().link(extracted.claim, task.bundle)
    assert extracted.claim == before
    assert extracted.claim.evidence_links == []
    assert result.claim.evidence_links == result.links


def test_linker_is_deterministic_across_runs() -> None:
    task = loader.load_task(TASKS_DIR / "ml_claims" / "synthetic_data_passage.yaml")
    extracted = RuleBasedClaimExtractor().extract(task.input_claim, task.bundle)
    first = EvidenceLinker().link(extracted.claim, task.bundle)
    second = EvidenceLinker().link(extracted.claim, task.bundle)
    assert first.links == second.links
    assert first.rules_fired == second.rules_fired
    assert first.passage_candidates == second.passage_candidates


