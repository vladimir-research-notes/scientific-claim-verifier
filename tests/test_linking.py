def test_tokenize_keeps_hyphenated_names_and_decimals() -> None:
    # "SST-2" and "72.0" are single tokens; a filename survives intact.
    assert passages.tokenize("SST-2 hits 72.0 via compute_accuracy.py") == [
        "sst-2",
        "hits",
        "72.0",
        "via",
        "compute_accuracy.py",
    ]


def test_tokenize_strips_punctuation_and_percent() -> None:
    assert passages.tokenize("reaches 90% accuracy, as shown.") == [
        "reaches",
        "90",
        "accuracy",
        "as",
        "shown",
    ]


def test_content_tokens_drop_stopwords_but_keep_negation_and_quantifiers() -> None:
    tokens = passages.content_tokens("The model is trained only on synthetic data; no real corpus.")
    assert tokens == {"model", "trained", "only", "synthetic", "data", "no", "real", "corpus"}


def test_dice_identical_disjoint_and_empty() -> None:
    assert passages.dice({"a", "b"}, {"a", "b"}) == 1.0
    assert passages.dice({"a"}, {"b"}) == 0.0
    assert passages.dice(set(), set()) == 0.0
    assert passages.dice({"a"}, set()) == 0.0


def test_dice_is_symmetric_and_bounded() -> None:
    left, right = {"a", "b", "c"}, {"b", "c", "d", "e"}
    score = passages.dice(left, right)
    assert score == passages.dice(right, left)
    assert 0.0 < score < 1.0


def test_contains_claim_ignores_line_wrapping_and_trailing_period() -> None:
    # A YAML-folded passage wraps across lines; the claim is one line with a period.
    assert passages.contains_claim(
        "Method A improves accuracy on SST-2.",
        "Method A improves accuracy on\nSST-2, as shown in Table 1.",
    )


def test_contains_claim_false_for_paraphrase() -> None:
    assert not passages.contains_claim(
        "The model is trained only on synthetic data.",
        "All experiments use synthetic data generated by our pipeline.",
    )


def test_split_sentences_does_not_split_on_decimal_points() -> None:
    assert passages.split_sentences("Accuracy is 78.0 here. It rose from 72.0.") == [
        "Accuracy is 78.0 here.",
        "It rose from 72.0.",
    ]


def test_best_sentence_picks_the_overlapping_sentence() -> None:
    quote = passages.best_sentence(
        "The model is trained on synthetic data.",
        "Training ran on one CPU. All experiments use synthetic data from our pipeline.",
    )
    assert quote == "All experiments use synthetic data from our pipeline."


def test_best_sentence_none_for_empty_passage() -> None:
    assert passages.best_sentence("anything", "   ") is None


