"""Milestone 4 — evidence linker tests (CPU-only, offline).

Two layers, mirroring ``tests/test_extraction.py``:

1. **Unit tests** for each evidence channel on small synthetic bundles — the
   tokenizer and Dice overlap, exact passage lookup, the ranking and its
   tie-breaks, the table row rule (a cell link requires the claim to *name* the
   row), dataset measured-column selection, code resolution, and figure series
   matching — independently of any fixture.
2. **Integration tests** running the linker over the real committed fixtures and
   scoring against each task's gold ``expected.evidence``, both *blind* (ignoring
   the declared ``source_passage``, which is the setting that actually measures
   retrieval) and with the declared source honoured.
"""

from __future__ import annotations

import json
from pathlib import Path

from scientific_claim_verifier import cli
from scientific_claim_verifier import schemas as S
from scientific_claim_verifier.artifacts import loader
from scientific_claim_verifier.claims import linking
