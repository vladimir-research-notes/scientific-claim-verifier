def results_table() -> S.Table:
    return S.Table(
        table_id="t1",
        columns=["method", "accuracy"],
        rows=[["baseline", 72.0], ["A", 78.0]],
    )


def split_table() -> S.Table:
    return S.Table(
        table_id="t2",
        columns=["split", "accuracy"],
        rows=[["dev", 90.0], ["test", 82.0]],
    )


def test_normalize_header_canonicalizes_spaces_and_hyphens() -> None:
    assert ev_tables.normalize_header("  F1 Score ") == "f1_score"
    assert ev_tables.normalize_header("GC-content") == "gc_content"


def test_header_matches_metric_through_the_extractor_lexicon() -> None:
    assert ev_tables.header_matches_metric("F1 Score", ["f1"])
    assert ev_tables.header_matches_metric("accuracy", ["accuracy"])


def test_header_matches_metric_rejects_label_columns() -> None:
    assert not ev_tables.header_matches_metric("method", ["accuracy"])
    assert not ev_tables.header_matches_metric("split", ["accuracy"])
    assert not ev_tables.header_matches_metric("accuracy", [])


def test_label_column_index_finds_the_all_string_column() -> None:
    assert ev_tables.label_column_index(results_table()) == 0


def test_label_column_index_none_without_a_string_column() -> None:
    numeric = S.Table(table_id="t", columns=["a", "b"], rows=[[1.0, 2.0]])
    assert ev_tables.label_column_index(numeric) is None
    assert ev_tables.label_column_index(S.Table(table_id="t", columns=["a"])) is None


def test_claim_names_row_via_extracted_entity() -> None:
    claim = make_claim("Method A improves accuracy.", entities=["Method A", "baseline"])
    assert ev_tables.claim_names_row("A", claim)
    assert ev_tables.claim_names_row("baseline", claim)


def test_claim_names_row_short_label_is_case_sensitive() -> None:
    # A lowercase article "a" must not name a row called "A"; a capitalized one does.
    assert not ev_tables.claim_names_row("A", make_claim("a method reaches 90% accuracy"))
    assert ev_tables.claim_names_row("A", make_claim("Method A reaches 90% accuracy"))


def test_claim_names_row_false_positive_on_sentence_initial_article() -> None:
    """A documented limitation, pinned so a future fix shows up as a test change.

    Case-sensitivity cannot distinguish the row label ``A`` from the article "A"
    at the start of a sentence. The claim below names no row, yet ``A`` matches.
    See ``docs/EVIDENCE_LINKING.md``.
    """
    assert ev_tables.claim_names_row("A", make_claim("A method reaches 90% accuracy."))


def test_claim_names_row_rejects_unmentioned_split() -> None:
    claim = make_claim("The method reaches 90% accuracy.", metrics=["accuracy"])
    assert not ev_tables.claim_names_row("dev", claim)
    assert not ev_tables.claim_names_row("test", claim)


def test_claim_names_row_rejects_stopword_labels() -> None:
    assert not ev_tables.claim_names_row("the", make_claim("the method reaches 90% accuracy"))


def test_link_table_emits_a_cell_per_named_row() -> None:
    claim = make_claim(
        "Method A improves accuracy from 72.0 to 78.0 over the baseline.",
        CT.COMPARISON,
        entities=["Method A", "baseline"],
        metrics=["accuracy"],
        expected_value=78.0,
        baseline_value=72.0,
    )
    matches = ev_tables.link_table(claim, results_table())
    assert [(m.locator, m.method) for m in matches] == [
        ("row=A,col=accuracy", MatchMethod.TABLE_CELL),
        ("row=baseline,col=accuracy", MatchMethod.TABLE_CELL),
    ]


def test_link_table_falls_back_to_the_column_when_no_row_is_named() -> None:
    # 90.0 matches exactly one cell (row "dev"), but the claim never says "dev".
    # Linking the cell would invent a row the claim did not choose.
    claim = make_claim(
        "The method reaches 90% accuracy.", metrics=["accuracy"], expected_value=90.0
    )
    matches = ev_tables.link_table(claim, split_table())
    assert [(m.locator, m.method) for m in matches] == [("col=accuracy", MatchMethod.TABLE_COLUMN)]


def test_link_table_still_links_the_column_when_no_cell_matches() -> None:
    # A contradicted claim must remain checkable, so the column is linked anyway.
    claim = make_claim(
        "The method reaches 95% accuracy.", metrics=["accuracy"], expected_value=95.0
    )
    matches = ev_tables.link_table(claim, split_table())
    assert [m.locator for m in matches] == ["col=accuracy"]
    assert matches[0].matched_value is None


def test_link_table_empty_when_no_column_carries_a_claim_metric() -> None:
    claim = make_claim("The method reaches an F1 of 0.9.", metrics=["f1"], expected_value=0.9)
    assert ev_tables.link_table(claim, split_table()) == []


def test_link_tables_sole_table_mention_fallback() -> None:
    claim = make_claim("The result is shown in Table 1.", CT.TABLE)
    matches = ev_tables.link_tables(claim, [split_table()], figure_or_table_mentioned=True)
    assert [(m.table_id, m.locator, m.method) for m in matches] == [
        ("t2", None, MatchMethod.TABLE_MENTION)
    ]
    # Without a mention there is nothing to justify the link.
    assert ev_tables.link_tables(claim, [split_table()], figure_or_table_mentioned=False) == []


