def test_rank_passages_prefers_exact_text_over_a_higher_overlap_rival() -> None:
    # p_rival has *perfect* token overlap (same content words, reordered) but does
    # not state the claim; p_verbatim does, buried in a long passage that scores
    # poorly on Dice. The verbatim passage must win.
    bundle = make_bundle(
        papers=[
            paper(
                ("p_rival", "Accuracy of the method reaches 90."),
                (
                    "p_verbatim",
                    "In this work the method reaches 90% accuracy, and we note that seeds, "
                    "preprocessing, and the evaluation harness were held fixed throughout "
                    "every experimental condition we report below.",
                ),
            )
        ]
    )
    ranked = passages.rank_passages("The method reaches 90% accuracy.", bundle)
    assert ranked[0].passage_id == "p_verbatim"
    assert ranked[0].method is MatchMethod.EXACT_TEXT
    assert ranked[0].score == 1.0
    # The rival's raw overlap is perfect, yet it ranks second: method beats score.
    assert ranked[1].overlap_score == 1.0
    assert ranked[0].overlap_score < ranked[1].overlap_score


def test_rank_passages_blind_beats_distractor_by_overlap() -> None:
    bundle = make_bundle(
        papers=[
            paper(
                ("p_data", "All experiments use synthetic data generated by our pipeline."),
                ("p_hardware", "Training ran on a single CPU node; no GPU was required."),
            )
        ]
    )
    ranked = passages.rank_passages("The model is trained only on synthetic data.", bundle)
    assert [c.passage_id for c in ranked] == ["p_data", "p_hardware"]
    assert ranked[0].method is MatchMethod.TOKEN_OVERLAP
    assert ranked[1].overlap_score == 0.0


def test_rank_passages_declared_source_is_promoted_but_overlap_still_reported() -> None:
    bundle = make_bundle(
        papers=[paper(("p_weak", "An unrelated sentence about hardware."), ("p_x", "Other text."))]
    )
    ranked = passages.rank_passages("Synthetic data only.", bundle, declared_passage_id="p_weak")
    assert ranked[0].passage_id == "p_weak"
    assert ranked[0].method is MatchMethod.DECLARED_SOURCE
    assert ranked[0].score == 1.0
    # The measured overlap is preserved, so an asserted-but-poor link is visible.
    assert ranked[0].overlap_score == 0.0


def test_rank_passages_tie_breaks_on_passage_id_for_determinism() -> None:
    bundle = make_bundle(papers=[paper(("p_b", "unrelated words"), ("p_a", "unrelated words"))])
    ranked = passages.rank_passages("nothing shared", bundle)
    assert [c.passage_id for c in ranked] == ["p_a", "p_b"]


def test_select_passage_rejects_everything_below_the_floor() -> None:
    bundle = make_bundle(papers=[paper(("p1", "completely unrelated prose"))])
    ranked = passages.rank_passages("orthogonal claim tokens", bundle)
    assert passages.select_passage(ranked) is None


def test_select_passage_none_when_bundle_has_no_papers() -> None:
    assert passages.select_passage(passages.rank_passages("x", make_bundle())) is None


