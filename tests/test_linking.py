REPO_ROOT = Path(__file__).resolve().parents[1]
TASKS_DIR = REPO_ROOT / "tasks"

CT = S.ClaimType
EK = S.EvidenceKind


# ---------------------------------------------------------------------------
# Builders for small synthetic bundles (no fixture files touched)
# ---------------------------------------------------------------------------


def make_claim(text: str, claim_type: S.ClaimType = CT.NUMERIC, **kwargs) -> S.ScientificClaim:
    return S.ScientificClaim(claim_id="c1", claim_text=text, claim_type=claim_type, **kwargs)


def make_bundle(**kwargs) -> S.ArtifactBundle:
    return S.ArtifactBundle(bundle_id="b1", **kwargs)


def paper(*passages_: tuple[str, str]) -> S.PaperArtifact:
    return S.PaperArtifact(
        artifact_id="paper1",
        passages=[S.Passage(passage_id=pid, text=text) for pid, text in passages_],
    )


def linked(links: list[S.EvidenceLink], kind: S.EvidenceKind) -> list[S.EvidenceLink]:
    return [link for link in links if link.kind is kind]


def load_all_tasks() -> list[loader.LoadedTask]:
    return [loader.load_task(path) for path in loader.discover_task_files(TASKS_DIR)]


def link_task(task: loader.LoadedTask, *, blind: bool) -> linking.Linking:
    """Run the M3 extractor then the M4 linker, as the pipeline does."""
    extracted = RuleBasedClaimExtractor().extract(task.input_claim, task.bundle)
    return EvidenceLinker(use_declared_source=not blind).link(extracted.claim, task.bundle)


