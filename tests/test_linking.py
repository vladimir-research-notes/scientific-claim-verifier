def link(kind: S.EvidenceKind, target: str, locator: str | None = None) -> S.EvidenceLink:
    return S.EvidenceLink(kind=kind, target_id=target, locator=locator)


def test_score_linking_exact_match() -> None:
    gold = [link(EK.PASSAGE, "p1"), link(EK.TABLE, "t1", "col=accuracy")]
    score = linking.score_linking(list(gold), gold)
    assert score.strict.exact
    assert (score.strict.tp, score.strict.fp, score.strict.fn) == (2, 0, 0)
    assert score.strict.precision == score.strict.recall == score.strict.f1 == 1.0


def test_score_linking_reports_missing_and_spurious() -> None:
    gold = [link(EK.PASSAGE, "p1"), link(EK.TABLE, "t1", "row=A,col=accuracy")]
    predicted = [link(EK.PASSAGE, "p1"), link(EK.TABLE, "t1", "col=accuracy")]
    score = linking.score_linking(predicted, gold)
    assert score.strict.missing == ("table:t1:row=A,col=accuracy",)
    assert score.strict.spurious == ("table:t1:col=accuracy",)
    assert not score.strict.exact
    # Loosely, the right table was found — only the locator was wrong.
    assert score.loose.exact


def test_score_linking_loose_keys_collapse_two_cells_of_one_table() -> None:
    gold = [link(EK.TABLE, "t1", "row=A,col=acc"), link(EK.TABLE, "t1", "row=b,col=acc")]
    score = linking.score_linking(list(gold), gold)
    assert score.strict.tp == 2
    assert score.loose.tp == 1


def test_set_score_precision_is_vacuously_one_when_nothing_predicted() -> None:
    score = linking.score_linking([], [link(EK.PASSAGE, "p1")])
    assert score.strict.precision == 1.0
    assert score.strict.recall == 0.0
    assert score.strict.f1 == 0.0
    assert score.strict.fn == 1


def test_aggregate_linking_scores_sums_counts() -> None:
    a = linking.score_linking([link(EK.PASSAGE, "p1")], [link(EK.PASSAGE, "p1")])
    b = linking.score_linking([], [link(EK.TABLE, "t1")])
    total = linking.aggregate_linking_scores([a, b])
    assert (total.strict.tp, total.strict.fp, total.strict.fn) == (1, 0, 1)
    assert total.strict.recall == 0.5


