def test_blind_linking_reproduces_every_gold_link() -> None:
    """The headline number: without the declared source_passage, 14/14 gold links."""
    scores = []
    for task in load_all_tasks():
        result = link_task(task, blind=True)
        score = linking.score_linking(result.links, task.spec.expected.evidence)
        assert score.strict.exact, (
            f"{task.spec.task_id}: missing={score.strict.missing} "
            f"spurious={score.strict.spurious}"
        )
        scores.append(score)
    total = linking.aggregate_linking_scores(scores)
    assert (total.strict.tp, total.strict.fp, total.strict.fn) == (14, 0, 0)


def test_declared_source_linking_also_reproduces_every_gold_link() -> None:
    for task in load_all_tasks():
        result = link_task(task, blind=False)
        score = linking.score_linking(result.links, task.spec.expected.evidence)
        assert score.strict.exact, task.spec.task_id


def test_declared_source_is_labelled_as_asserted_not_discovered() -> None:
    task = loader.load_task(TASKS_DIR / "ml_claims" / "synthetic_data_passage.yaml")
    declared = link_task(task, blind=False).links[0]
    blind = link_task(task, blind=True).links[0]
    assert declared.target_id == blind.target_id == "p_data"
    assert "match=declared_source_passage" in (declared.notes or "")
